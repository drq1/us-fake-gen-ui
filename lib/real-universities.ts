export function getRealUniversity(stateCode?: string, seed?: number): UniversityData {
  const code = stateCode?.toUpperCase() || "CA"
  const list = VERIFIED_UNIVERSITIES[code] || VERIFIED_UNIVERSITIES.WI || VERIFIED_UNIVERSITIES.CA
  const index = seed !== undefined ? Math.abs(seed) % list.length : Math.floor(Math.random() * list.length)
  return list[index]
}
